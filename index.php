    $('#contactForm').on('submit', function(e) {
      e.preventDefault();

      $('.loading').removeClass('d-none');
      $('.error-message').addClass('d-none').text('');
      $('.msgSuccess').addClass('d-none');

      $.ajax({
        url: 'contact_handler.php',
        method: 'POST',
        data: $(this).serialize(),
        success: function(response) {
          $('.loading').addClass('d-none');
          if (response.status === 'success') {
            $('.msgSuccess').removeClass('d-none');
            $('#contactForm')[0].reset();
          } else {
            $('.error-message').removeClass('d-none').text(response.message);
          }
        },
        error: function() {
          $('.loading').addClass('d-none');
          $('.error-message').removeClass('d-none').text('An error occurred while sending the message.');
        }
      });
    });
  </script>

